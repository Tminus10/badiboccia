<div class="page-head"><div><h1>Rules</h1></div></div>

<section class="card rules-card">
  <h2>Group Stage</h2>
  <p>
    In the group stage, every team plays every other team in its group once.
    A game is played to <strong>two winning sets</strong> of <strong>15 points</strong> each – the first
    team to win two sets wins the game.
  </p>

  <h2>Points for the Standings</h2>
  <ul>
    <li><strong>Win 2:0</strong> – 3 points, <strong>loss 0:2</strong> – 0 points</li>
    <li><strong>Win 2:1</strong> – 2 points, <strong>loss 1:2</strong> – 1 point</li>
    <li><strong>Draw 1:1</strong> – 1 point each (if a game can't be finished, e.g. because of the weather)</li>
  </ul>

  <h2>Quarter-finals and Knockout Stage</h2>
  <p>
    The top two teams of each group reach the quarter-finals. From there on it's
    a knockout – quarter-final, semi-final, final – and sets go to
    <strong>21 points</strong>. The two losers of the semi-finals also play each other in the
    <strong>third-place game</strong>.
  </p>

  <h2>Scheduling</h2>
  <p>
    You arrange the dates of your games directly with your opponent.
    All <strong>group games</strong> must be played <strong>by the end of July</strong>, so that
    there's enough time left for the knockout stage.
  </p>
</section>
